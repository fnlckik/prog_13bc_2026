        // Backtrack - One solution
        // Hatékonyság? nxm-es táblázat esetén
        // O(4^(n*m))
        static bool BacktrackSearch(List<List<char>> board, int i, int j)
        {
            //Show(board);
            bool finished = board[i][j] == 'C';
            if (finished)
            {
                Show(board);
                return true;
            }
            if (TryStep2(board, i, j + 1, 'L')) return true; // jobbra
            if (TryStep2(board, i + 1, j, 'T')) return true; // lefelé
            if (TryStep2(board, i, j - 1, 'R')) return true; // balra
            if (TryStep2(board, i - 1, j, 'B')) return true; // felfelé
            return false;
        }

        static bool TryStep2(List<List<char>> board, int i, int j, char d)
        {
            if (IsValid(board, i, j))
            {
                Step(board, i, j, d);
                if (BacktrackSearch(board, i, j)) return true;
                Back(board, i, j);
            }
            return false;
        }

        // Backtrack - All solution
        static void Backtrack(List<List<char>> board, int i, int j)
        {
            //Show(board);
            bool finished = board[i][j] == 'C';
            if (finished)
            {
                Show(board);
                return;
            }
            TryStep(board, i, j + 1, 'L'); // jobbra
            TryStep(board, i + 1, j, 'T'); // lefelé
            TryStep(board, i, j - 1, 'R'); // balra
            TryStep(board, i - 1, j, 'B'); // felfelé
        }

        static void TryStep(List<List<char>> board, int i, int j, char d)
        {
            if (IsValid(board, i, j))
            {
                Step(board, i, j, d);
                Backtrack(board, i, j);
                Back(board, i, j);
            }
        }

        static void Back(List<List<char>> board, int i, int j)
        {
            if (board[i][j] == 'C') return; // Ne írjuk felül a célt!
            board[i][j] = '.';
        }

        static void Step(List<List<char>> board, int i, int j, char d)
        {
            if (board[i][j] == 'C') return; // Ne írjuk felül a célt!
            board[i][j] = d; // 'X'
        }

        // if (board[i][j] == '#') return false; // falba nem megyünk
        // if (board[i][j] == 'X') return false; // nem lépünk oda, ahol már voltunk
        static bool IsValid(List<List<char>> board, int i, int j)
        {
            if (i < 0 || i >= board.Count || j < 0 || j >= board[i].Count) return false;
            if (board[i][j] != '.' && board[i][j] != 'C') return false;
            return true;
        }

        static void Show(List<List<char>> board)
        {
            foreach (var row in board)
            {
                foreach (var e in row)
                {
                    if (e == 'X') Console.ForegroundColor = ConsoleColor.Green;
                    else if (e == '#') Console.ForegroundColor = ConsoleColor.Red;
                    else Console.ForegroundColor = ConsoleColor.White;
                    Console.Write(e + " ");
                    Console.ForegroundColor = ConsoleColor.White;
                }
                Console.WriteLine();
            }
            Console.WriteLine();
        }
